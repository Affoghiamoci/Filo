# Barra proprietà: sezioni comprimibili (stato ricordato, Posizione/Misure in sincronia), freccia "altro sotto"; Riquadro prende anche i pezzi coperti
from playwright.sync_api import sync_playwright
ok=True
def check(name,cond):
    global ok; ok=ok and bool(cond); print('OK ' if cond else 'KO ',name)
URL='file:///tmp/forma/dist/forma.html'
HEADS="[...document.querySelectorAll('#p-scroll h4.ph')].filter(h=>h.offsetParent).map(h=>h.dataset.k)"
with sync_playwright() as p:
    b=p.chromium.launch(args=["--use-gl=swiftshader"]); errs=[]
    pg=b.new_page(viewport={'width':1280,'height':760}); pg.on('pageerror',lambda e:errs.append(str(e)))
    pg.goto(URL);pg.wait_for_function("window.forma");pg.wait_for_timeout(800)
    pg.evaluate("(()=>{const f=forma;f.setSelection([f.createObject('box'),f.createObject('cylinder')])})()");pg.wait_for_timeout(400)
    hs=pg.evaluate(HEADS)
    check('ordine sezioni (gruppo)',hs[:4]==['colore','posizione','misure','rotazione'] and 'allinea' not in hs)
    check('Allinea è dentro Posizione',pg.evaluate("!!document.querySelector('#p-pos #p-align')"))
    check('Solido/Foro non è più nel pannello',pg.evaluate("!document.querySelector('#p-type')"))
    check('11 colori',pg.evaluate("document.querySelectorAll('#p-color-sw .sw').length")==11)
    check('mm minuscolo nelle intestazioni',pg.evaluate("[...document.querySelectorAll('#p-scroll h4 .u')].every(u=>getComputedStyle(u).textTransform==='none')"))
    check('Ruota di 90° nella stessa sezione di Rotazione',pg.evaluate("!!document.querySelector('#p-rotq [data-rq=x]')&&!!document.querySelector('#p-rotq #p-rot-s')"))
    check('la freccia "altro sotto" compare quando c\'è altro da scorrere',pg.evaluate("!document.querySelector('#p-more').classList.contains('hidden')"))
    pg.evaluate("document.querySelector('#p-scroll').scrollTop=9999");pg.wait_for_timeout(200)
    check('in fondo la freccia sparisce',pg.evaluate("document.querySelector('#p-more').classList.contains('hidden')"))
    pg.evaluate("document.querySelector('#p-scroll').scrollTop=0");pg.wait_for_timeout(100)
    pg.evaluate("[...document.querySelectorAll('#p-scroll h4.ph')].find(h=>h.offsetParent&&h.dataset.k==='posizione').click()");pg.wait_for_timeout(200)
    pg.evaluate("[...document.querySelectorAll('#p-scroll h4.ph')].find(h=>h.offsetParent&&h.dataset.k==='colore').click()");pg.wait_for_timeout(200)
    check('clic su Colore nasconde i colori',pg.evaluate("document.querySelector('#p-color-sw').offsetParent===null"))
    pg.evaluate("[...document.querySelectorAll('#p-scroll h4.ph')].find(h=>h.offsetParent&&h.dataset.k==='colore').click()");pg.wait_for_timeout(200)
    check('secondo clic su Colore li mostra di nuovo',pg.evaluate("document.querySelector('#p-color-sw').offsetParent!==null"))
    check('clic sull\'intestazione comprime la sezione',pg.evaluate("document.querySelector('#g-x').offsetParent===null"))
    pg.evaluate("forma.setSelection([forma.objects[0]])");pg.wait_for_timeout(300)
    check('Posizione dell\'oggetto singolo resta in sincronia',pg.evaluate("document.querySelector('#p-x').offsetParent===null"))
    pg.reload();pg.wait_for_function("window.forma");pg.wait_for_timeout(800)
    pg.evaluate("forma.createObject('box')");pg.wait_for_timeout(300)
    check('lo stato resta dopo il ricaricamento',pg.evaluate("document.querySelector('#p-x').offsetParent===null"))
    pg.focus("#p-scroll h4.ph[data-k=posizione]");pg.keyboard.press('Enter');pg.wait_for_timeout(200)
    check('Invio riapre la sezione',pg.evaluate("document.querySelector('#p-x').offsetParent!==null"))
    pg.evaluate("forma.setSelection(forma.objects.slice(0,1))");pg.wait_for_timeout(200)
    n0=pg.evaluate('forma.repeatPreviewCount')
    pg.evaluate("document.querySelector('#p-repeat h4.ph').click()");pg.focus('#p-repeat h4.ph');pg.wait_for_timeout(250)
    check('comprimere Ripeti non accende l\'anteprima',n0==0 and pg.evaluate('forma.repeatPreviewCount')==0)
    pg.evaluate("document.querySelector('#p-repeat h4.ph').click()")
    pg.evaluate("(()=>{const f=forma;const a=[];for(let i=0;i<10;i++)a.push(f.createObject('box'));f.setSelection(a)})()");pg.wait_for_timeout(200)
    pg.fill('#rp-nx','5');pg.fill('#rp-ny','5');pg.wait_for_timeout(250)
    check('10 pezzi x 24 copie = 240 pezzi: nessun avviso e anteprima',pg.evaluate('forma.repeatPreviewCount')==240 and 'Troppi' not in pg.inner_text('#rp-info'))
    pg.fill('#rp-nx','20');pg.fill('#rp-ny','20');pg.wait_for_timeout(250)
    check('avviso con i numeri veri',pg.evaluate('forma.repeatPreviewCount')==0 and '1500' in pg.inner_text('#rp-info') and '10 ×' in pg.inner_text('#rp-info'))
    pg.set_viewport_size({'width':1280,'height':600});pg.wait_for_timeout(300)
    check('freccia anche nella sidebar sinistra',pg.evaluate("!document.querySelector('#t-more').classList.contains('hidden')"))
    check('nessun errore di pagina',not errs)
    b.close()
print('TUTTO OK' if ok else 'FALLITO')
