from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    b=p.chromium.launch(args=["--use-gl=swiftshader","--enable-webgl","--ignore-gpu-blocklist"])
    pg=b.new_context(viewport={'width':1440,'height':900}).new_page()
    errs=[]; pg.on('pageerror',lambda e:errs.append(str(e)))
    pg.goto('file:///tmp/forma/dist/forma.html'); pg.wait_for_timeout(500); pg.screenshot(path='shots/welcome.png')
    pg.click('[data-eh=text]'); pg.wait_for_timeout(500)
    pg.click('#t-font-b'); pg.wait_for_timeout(500); pg.screenshot(path='shots/fontsel.png')
    pg.click('#t-font-l [data-f=bebas]'); pg.wait_for_timeout(500)
    print(pg.evaluate("()=>window.forma.objects.map(o=>JSON.stringify(o.userData.text))"))
    pg.click('#b-history'); pg.wait_for_timeout(300)
    pg.evaluate("()=>{const f=window.forma;f.objects[0].position.x+=10;f.objects[0].updateMatrixWorld(true)}")
    pg.fill('#t-size','20'); pg.press('#t-size','Enter'); pg.wait_for_timeout(500)
    pg.screenshot(path='shots/hist.png')
    print(pg.evaluate("()=>[...document.querySelectorAll('.hrow')].map(r=>r.textContent)"))
    pg.click('.hrow:nth-child(2)'); pg.wait_for_timeout(300)
    print(pg.evaluate("()=>window.forma.objects.length"), errs); b.close()
