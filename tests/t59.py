# Strumenti in seconda funzione: gruppi, menu laterale, ricordo dell'ultimo, Esc, sidebar stretta
from playwright.sync_api import sync_playwright
ok=True
def check(name,cond):
    global ok; ok=ok and bool(cond); print('OK ' if cond else 'KO ',name)
with sync_playwright() as p:
    b=p.chromium.launch(args=["--use-gl=swiftshader"]);pg=b.new_page(viewport={'width':1400,'height':850})
    errs=[];pg.on('pageerror',lambda e:errs.append(str(e)))
    pg.goto('file:///tmp/forma/dist/forma.html');pg.wait_for_function("window.forma");pg.wait_for_timeout(900)
    G=lambda g:pg.evaluate(f"(()=>{{const b=document.querySelector('#tools .grp[data-g={g}]');return [b.querySelector('b').textContent,b.classList.contains('active')]}})()")
    fly=lambda:pg.evaluate("(()=>{const f=document.querySelector('#flyout');return f.classList.contains('hidden')?null:[...f.querySelectorAll('b')].map(x=>x.textContent)})()")
    names=pg.evaluate("[...document.querySelectorAll('#tools .tool')].map(b=>b.querySelector('b').textContent)")
    check('Lazo, Allunga e Interseca non sono in barra',not {'Lazo','Allunga','Interseca'}&set(names))
    check('Testo e ultimo tra le forme',names.index('Testo')==names.index('Toro')+1 and names.index('Testo')<names.index('Foro / Solido'))
    pg.locator('#tools .grp[data-g=sel] .gtri').click();pg.wait_for_timeout(200)
    check('triangolino apre il menu',fly()==['Riquadro','Lazo'])
    pg.locator('#flyout .tool').nth(1).click();pg.wait_for_timeout(150)
    check('scegliere Lazo: attivo e mostrato',pg.evaluate('forma.state.tool')=='lasso' and G('sel')==['Lazo',True] and fly() is None)
    pg.keyboard.press('q');pg.wait_for_timeout(100);check('Q resta diretto',pg.evaluate('forma.state.tool')=='marquee' and G('sel')[0]=='Riquadro')
    pg.keyboard.press('u');pg.wait_for_timeout(100);check('U attiva Allunga e il gruppo lo mostra',pg.evaluate('forma.state.tool')=='stretch' and G('plane')==['Allunga',True])
    pg.locator('#tools .grp[data-g=comb]').click(button='right');pg.wait_for_timeout(200)
    check('clic destro: Combina e Interseca',fly()==['Combina','Interseca'])
    pg.keyboard.press('Escape');pg.wait_for_timeout(100);check('Esc chiude il menu',fly() is None)
    pg.locator('#tools .grp[data-g=comb]').click(button='right');pg.mouse.click(900,400);pg.wait_for_timeout(100);check('clic fuori chiude',fly() is None)
    check('Combina resta sempre Combina',G('comb')[0]=='Combina')
    bx=pg.locator('#tools .grp[data-g=sel]').bounding_box();pg.mouse.move(bx['x']+60,bx['y']+15);pg.mouse.down();pg.wait_for_timeout(600);pg.mouse.up();pg.wait_for_timeout(150)
    check('pressione lunga apre il menu senza lanciare lo strumento',fly()==['Riquadro','Lazo'] and pg.evaluate('forma.state.tool')=='stretch')
    pg.keyboard.press('Escape')
    pg.locator('#tools .grp[data-g=plane]').focus();pg.keyboard.press('ArrowRight');pg.wait_for_timeout(100)
    check('freccia destra apre e porta il fuoco',fly()==['Taglia','Allunga'] and pg.evaluate("document.activeElement.closest('#flyout')!==null"))
    pg.keyboard.press('Escape');pg.keyboard.press('Tab');pg.wait_for_timeout(500)
    pg.locator('#tools .grp[data-g=sel] .gtri').click();pg.wait_for_timeout(200)
    check('sidebar stretta: menu aperto a destra',fly()==['Riquadro','Lazo'] and pg.evaluate("document.querySelector('#flyout').getBoundingClientRect().left>=60"))
    pg.keyboard.press('Tab');pg.wait_for_timeout(300);check('Tab chiude il menu',fly() is None)
    pg.reload();pg.wait_for_function("window.forma");pg.wait_for_timeout(800)
    check('ricorda l\'ultimo dopo il ricaricamento',G('sel')[0]=='Riquadro' and G('plane')[0]=='Allunga')
    check('nessun errore',not errs)
    b.close()
print('TUTTO OK' if ok else 'FALLITO')
